export function getFactsheetUrl(districtName) {
  if (!districtName) return null;
  const match = districtName.match(/^(.*)\s+(\d+(?:st|nd|rd|th)|At-Large)$/i);
  if (!match) return null;
  
  const stateName = match[1].trim();
  const districtStr = match[2];
  
  const stateAbbr = STATE_ABBREVIATIONS[stateName];
  if (!stateAbbr) return null;
  
  let districtNum = "00";
  if (districtStr.toLowerCase() !== "at-large") {
    const num = parseInt(districtStr, 10);
    if (!isNaN(num)) {
      districtNum = num < 10 ? `0${num}` : `${num}`;
    }
  }
  
  const code = `${stateAbbr}${districtNum}`;
  return FACTSHEET_URLS[code] || null;
}